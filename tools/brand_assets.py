"""Measure the wordmarks in `brand/` and derive the icons from the mark.

    uv run --with pillow python tools/brand_assets.py

**Optional.** The app runs with no artwork at all, and with artwork it runs
without ever being told the artwork's size - `web/style.css` declares a
default for every variable this writes. What the tool buys you is that the
title card is sized from *your* files rather than from those defaults, so
larger wordmarks make the card larger by themselves and no number in the
stylesheet describes a file that happens to be there today.

It reads and writes `brand/`, which is gitignored:

    brand/wordmark-en.png  ->  web/brand-sizes.css   their native sizes, as
    brand/wordmark-ar.png                            CSS variables
    brand/mark.png         ->  brand/favicon-32.png            the browser tab
                               brand/apple-touch-icon-180.png  a home screen

Anything you supply yourself is left alone: the two icons are only derived
when they are absent, so dropping in your own `favicon-32.png` beats whatever
this would have produced. `--force` overwrites them anyway.

The wordmarks themselves are **never resized and never rewritten**. Whatever
you provide is what gets served, so the page always draws the real artwork at
its real resolution and an upscale is never baked into a file. The tool only
measures them, and it measures the *ink* rather than the canvas: an exporter
that leaves a band of empty pixels above a wordmark would otherwise have the
page laying it out by a box with nothing in it.

Pillow is deliberately **not** a project dependency - `uv run --with pillow`
keeps it out of `pyproject.toml`, the same way the Playwright tools do.
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
BRAND = ROOT / "brand"
WEB = ROOT / "web"

#: The square mark, and what is derived from it.
MARK = "mark.png"

#: `(name, size, opaque)`. The browser tab keeps its alpha so a light theme
#: and a dark one both work; the Apple touch icon must be opaque, because iOS
#: composites it onto white and a transparent mark would vanish.
DERIVED = [
    ("favicon-32.png", 32, False),
    ("apple-touch-icon-180.png", 180, True),
]

#: Fraction of a derived icon's square left as margin around the mark. Small:
#: artwork often carries its own padding, and at 32px that padding is most of
#: the icon.
MARGIN = 0.04

#: What an opaque icon is composited onto. iOS draws the home screen icon on
#: whatever it likes, so the icon supplies its own ground.
OPAQUE_GROUND = (255, 255, 255, 255)

#: The generated stylesheet carrying each wordmark's native size into CSS.
#: Unitless, so the same variable serves `aspect-ratio` (which rejects
#: lengths) and `calc(... * 1px)` where a length is wanted.
SIZES_CSS = "brand-sizes.css"

WORDMARKS = {"en": "wordmark-en.png", "ar": "wordmark-ar.png"}

SIZES_HEADER = """/* Generated by tools/brand_assets.py - do not edit.
 *
 * The native pixel size of each wordmark in brand/, after trimming to its
 * visible ink. `web/style.css` sizes the title card, the corner mark and the
 * footer strip from these, so replacing artwork and re-running the tool is
 * the whole update - no stylesheet edit, and no literal left behind
 * describing the file that used to be there.
 *
 * This file is gitignored: it describes somebody's artwork, not this
 * project. `web/style.css` declares a default for every variable below, so a
 * clone without this file still lays out correctly.
 *
 * Unitless on purpose: `aspect-ratio` will not take a length, and
 * `calc(var(--wm-en-w) * 1px)` covers the places that want one.
 */
"""


def trim_to_ink(path: Path):
    """Crop a transparent-ground image to the pixels that actually show.

    On the alpha channel specifically. A fully transparent pixel can carry
    any colour underneath - exporters often leave white there - so asking the
    RGB channels where the artwork is would trim nothing at all on such a
    file, silently. Alpha is the only channel that answers "does this pixel
    show".
    """
    from PIL import Image

    rgba = Image.open(path).convert("RGBA")
    box = rgba.getchannel("A").getbbox()
    return rgba if box is None else rgba.crop(box)


def baseline_fraction(path: Path) -> float:
    """Where the artwork's densest band of ink ends, as a share of its height.

    This is the line the two scripts have to stand on. Centring their boxes
    gets within about 10% of it, because each script's spare room is lopsided
    in its own way - an Arabic wordmark carries dots below and a Latin one
    does not - so the rest is closed by measuring.

    "Densest band" rather than "lowest pixel" on purpose: the lowest pixel of
    an Arabic wordmark is a dot hanging below the line, and aligning on that
    would hang the whole word too high.
    """
    rgba = trim_to_ink(path)
    alpha = rgba.getchannel("A")
    # One pass over the raw band rather than a crop per row: faster on a
    # large master, and it avoids Pillow's deprecated per-image `getdata`.
    raw = alpha.tobytes()
    width, height = rgba.width, rgba.height
    rows = [sum(raw[y * width:(y + 1) * width]) for y in range(height)]
    if not rows or not max(rows):
        return 1.0
    floor = max(rows) * 0.25
    band = [y for y, total in enumerate(rows) if total >= floor]
    return (band[-1] + 1) / rgba.height if band else 1.0


def measure(brand_dir: Path) -> dict[str, tuple[int, int]]:
    """Each wordmark's trimmed size, for whichever ones are there."""
    sizes: dict[str, tuple[int, int]] = {}
    for key, name in WORDMARKS.items():
        path = brand_dir / name
        if not path.is_file():
            continue
        image = trim_to_ink(path)
        sizes[key] = (image.width, image.height)
    return sizes


def arabic_nudge(brand_dir: Path, sizes: dict) -> float | None:
    """How far to lift the Arabic mark, as a share of the lockup width.

    Rounded to a whole pixel at the lockup's own cap, so the lift is a
    translation the browser can do exactly rather than a resample.
    """
    if "en" not in sizes or "ar" not in sizes:
        return None
    en_base = baseline_fraction(brand_dir / WORDMARKS["en"])
    ar_base = baseline_fraction(brand_dir / WORDMARKS["ar"])

    en_w, en_h = sizes["en"]
    ar_w, ar_h = sizes["ar"]
    ratio = ar_w / en_w
    # Both marks drawn at the lockup width: where each baseline lands.
    en_px = en_h * en_base
    ar_px = (ar_h * ratio) * ar_base
    pixels = round(ar_px - en_px)
    return pixels / en_w


def write_sizes_css(web_dir: Path, brand_dir: Path,
                    sizes: dict[str, tuple[int, int]]) -> Path | None:
    """Write the measurements, or remove a stale file if there is nothing.

    Removing matters: a `brand-sizes.css` describing artwork that has been
    deleted would keep sizing the card to a file that is no longer served.
    """
    target = web_dir / SIZES_CSS
    if not sizes:
        if target.exists():
            target.unlink()
            print(f"  removed {target.relative_to(ROOT)} (no wordmarks found)")
        return None

    lines = [SIZES_HEADER, ":root {"]
    for key in ("ar", "en"):
        if key in sizes:
            width, height = sizes[key]
            lines.append(f"  --wm-{key}-w: {width};")
            lines.append(f"  --wm-{key}-h: {height};")
    if "en" in sizes and "ar" in sizes:
        ratio = sizes["ar"][0] / sizes["en"][0]
        lines += [
            "",
            "  /* The Arabic mark's width as a share of the Latin one, so the",
            "     title card is one knob and both marks land on their own",
            "     native resolution at the same moment. */",
            f"  --wm-ar-en-ratio: {ratio:.4f};",
        ]
        nudge = arabic_nudge(brand_dir, sizes)
        if nudge is not None:
            lines += [
                "",
                "  /* How far to lift the Arabic mark, as a share of the",
                "     lockup width, so the two scripts stand on one line.",
                "     Measured from the artwork, so redrawn marks",
                "     re-measure themselves. */",
                f"  --wm-ar-nudge: {nudge:.6f};",
            ]
    lines.append("}")
    target.write_text("\n".join(lines) + "\n", encoding="utf-8")
    return target


def build_icons(brand_dir: Path, force: bool) -> list[str]:
    """Derive the tab and home-screen icons from the square mark.

    Only when they are absent. An icon you drew yourself beats one this
    squeezed out of a larger file, and at 32px that difference is the whole
    icon.
    """
    from PIL import Image

    source = brand_dir / MARK
    if not source.is_file():
        return []

    mark = trim_to_ink(source)
    built = []
    for name, size, opaque in DERIVED:
        target = brand_dir / name
        if target.is_file() and not force:
            print(f"  kept {name} (already there; --force to replace)")
            continue
        side = max(mark.width, mark.height)
        inner = round(side * (1 + MARGIN * 2))
        square = Image.new("RGBA", (inner, inner), (0, 0, 0, 0))
        square.paste(mark, ((inner - mark.width) // 2,
                            (inner - mark.height) // 2), mark)
        icon = square.resize((size, size), Image.LANCZOS)
        if opaque:
            ground = Image.new("RGBA", icon.size, OPAQUE_GROUND)
            ground.alpha_composite(icon)
            icon = ground
        icon.save(target)
        built.append(name)
    return built


def main() -> int:
    parser = argparse.ArgumentParser(
        description="Measure brand/ wordmarks and derive the icons.")
    parser.add_argument("--brand", type=Path, default=BRAND,
                        help="where the artwork is (default: brand/)")
    parser.add_argument("--force", action="store_true",
                        help="replace derived icons that already exist")
    args = parser.parse_args()

    try:
        import PIL  # noqa: F401
    except ImportError:
        print("Pillow is not installed. It is not a project dependency, so:\n"
              "\n"
              "    uv run --with pillow python tools/brand_assets.py\n",
              file=sys.stderr)
        return 2

    brand_dir = args.brand
    if not brand_dir.is_dir():
        print(f"No {brand_dir.relative_to(ROOT) if brand_dir.is_relative_to(ROOT) else brand_dir} "
              f"directory, so there is no artwork to measure.\n"
              f"\n"
              f"That is a working state: the app runs on its neutral theme\n"
              f"and hides every empty image slot. To add artwork, create the\n"
              f"directory and drop files in under the names in\n"
              f"config/brand.example.json.", file=sys.stderr)
        return 1

    print(f"Reading {brand_dir}")
    sizes = measure(brand_dir)
    for key, (width, height) in sorted(sizes.items()):
        print(f"  {WORDMARKS[key]}: {width}x{height} of ink")

    built = build_icons(brand_dir, args.force)
    for name in built:
        print(f"  wrote {name}")

    written = write_sizes_css(WEB, brand_dir, sizes)
    if written:
        print(f"  wrote {written.relative_to(ROOT)}")

    if not sizes and not built:
        print("\nNothing to do. Expected at least one of:")
        for name in [MARK] + list(WORDMARKS.values()):
            print(f"  {brand_dir.name}/{name}")
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
